export const locales = Object.keys(dictionaries);
export const defaultLocale = 'en';

export function getDictionary(locale) {
  return dictionaries[locale] ?? dictionaries[defaultLocale];
}

/** Dotted-path lookup with fallback to the default locale. */
export function translate(locale, key) {
  const walk = (dict) =>
    key.split('.').reduce((node, part) => (node == null ? node : node[part]), dict);
  return walk(getDictionary(locale)) ?? walk(dictionaries[defaultLocale]) ?? key;
}

/** Set the preferred_locale cookie (spec.md §10.3). */
export function setLocaleCookie(locale) {
  document.cookie = `preferred_locale=${locale};path=/;max-age=${60 * 60 * 24 * 365};SameSite=Lax`;
}

/** Read the preferred_locale cookie. */
export function getLocaleCookie() {
  const match = document.cookie.match(/(?:^|;\s*)preferred_locale=(\w+)/);
  return match ? match[1] : null;
}
